#!/usr/bin/env python3
"""Generate the Hz/V exponential table: entry i = round(0x18FC0000 * 2^((i - 48) / 12)), i = 0..88.

Entry 48 is 1 V (6396 codes) in 16.16 fixed point; each 12 entries doubles the voltage."""
import sys

N = 89
vals = [round(0x18FC0000 * 2 ** ((i - 48) / 12)) for i in range(N)]
out = ["/* Generated by tools/gen_hzv_table.py - do not edit. */",
       "#define HZV_TABLE_SIZE %d" % N,
       "static const uint32_t hzv_table[HZV_TABLE_SIZE] = {"]
for k in range(0, N, 6):
    out.append("    " + ", ".join("0x%08Xu" % v for v in vals[k:k + 6]) + ",")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
